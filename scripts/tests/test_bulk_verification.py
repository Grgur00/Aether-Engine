@pytest.mark.parametrize("fail_worker", [False, True])
def test_paired_orchestration_preserves_failure_and_uses_isolated_sources(tmp_path, monkeypatch, fail_worker):
    import contextlib
    import os
    import subprocess
    from pathlib import Path

    current, baseline = tmp_path / "candidate", tmp_path / "baseline"
    manifest = tmp_path / "manifest.csv"
    manifest.write_text("fixed input\n")
    output, scratch = tmp_path / "results", tmp_path / "scratch"
    monkeypatch.setattr(diagnostic, "ROOT", current)
    monkeypatch.setattr(diagnostic, "baseline_identity", lambda root: {"sourceManifestSha256": "frozen"})
    monkeypatch.setattr(diagnostic, "verify", lambda root: (
        {"counts": [1200, 1260, 1323, 1389, 1458], "seed": 20260926}, [manifest]))
    monkeypatch.setattr(diagnostic, "workload_args", lambda *args: None)
    monkeypatch.setattr(diagnostic.base.workload, "load_sources", lambda args: [1])
    monkeypatch.setattr(diagnostic.base, "CanonicalTransform", lambda args: lambda item: item)
    monkeypatch.setattr(diagnostic.base, "tensor_digest", lambda values: "reference")
    monkeypatch.setattr(diagnostic, "check_capacity", lambda *args: None)

    @contextlib.contextmanager
    def campaign(root, protocol):
        root.mkdir()
        assert protocol["training"] is False and protocol["jfr"] is False
        yield {"protocolHash": "protocol", "environmentId": "host"}

    monkeypatch.setattr(diagnostic, "campaign", campaign)
    workers = []

    def worker(command, *, cwd, env, **kwargs):
        request_path = Path(command[command.index("--request") + 1])
        request = json.loads(request_path.read_text())
        arm = request["case"]["name"]
        workers.append(arm)
        assert cwd == (baseline if arm == "baseline" else current)
        assert env["PYTHONPATH"] == os.pathsep.join(str(cwd / p) for p in ("scripts", "clients/python"))
        assert "jfrFile" not in request and "layoutRegression" not in request
        store = Path(request["store"])
        store.mkdir()
        (store / "evidence").write_text("preserve on failure")
        if fail_worker and len(workers) == 3:
            raise subprocess.CalledProcessError(1, command)
        diagnostic.write_json(Path(command[command.index("--output") + 1]), report(arm, 0))

    monkeypatch.setattr(diagnostic.subprocess, "run", worker)
    if fail_worker:
        with pytest.raises(subprocess.CalledProcessError):
            diagnostic.run(output, baseline, 3, scratch)
        assert not (output / "completion.json").exists()
        assert len(list(scratch.glob("*/store/evidence"))) == 1
        assert len(list(output.glob("block-*/*/result.receipt.json"))) == 2
    else:
        diagnostic.run(output, baseline, 3, scratch)
        assert workers == ["baseline", "candidate", "candidate", "baseline", "baseline", "candidate"]
        assert json.loads((output / "summary.json").read_text())["complete"]
        assert len(list(output.glob("block-*/*/result.receipt.json"))) == 6
        assert not list(scratch.iterdir())
